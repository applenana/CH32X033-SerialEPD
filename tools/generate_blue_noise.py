"""Reproducible void-and-cluster blue-noise rank map; no third-party assets.
Reference: Ulichney 1993, https://cv.ulichney.com/papers/1993-void-cluster.pdf
Requires numpy. Generated ranks are shipped as Dart constants; no runtime dependency.
"""
from pathlib import Path
import numpy as np
N=128; COUNT=N*N
rng=np.random.default_rng(0x53455031)
a=np.minimum(np.arange(N),N-np.arange(N))
kernel=np.exp(-(a[:,None]**2+a[None,:]**2)/(2*1.5**2))
def field(mask):return np.fft.ifft2(np.fft.fft2(mask)*np.fft.fft2(kernel)).real
def stamp(i):return np.roll(np.roll(kernel,i//N,axis=0),i%N,axis=1)
def cluster(m,f):return np.argmax(np.where(m,f,-np.inf))
def void(m,f):return np.argmin(np.where(m,np.inf,f))
seed=np.zeros(COUNT,dtype=bool);seed[rng.choice(COUNT,COUNT//10,replace=False)]=True;seed=seed.reshape(N,N)
f=field(seed)
for iteration in range(COUNT*4):
 c=cluster(seed,f);seed.flat[c]=False;f-=stamp(c)
 v=void(seed,f);seed.flat[v]=True;f+=stamp(v)
 if c==v:break
else:raise RuntimeError('seed did not converge')
ranks=np.zeros((N,N),dtype=np.int32)
m=seed.copy();f=field(m)
for rank in range(int(seed.sum())-1,-1,-1):
 c=cluster(m,f);ranks.flat[c]=rank;m.flat[c]=False;f-=stamp(c)
m=seed.copy();f=field(m)
for rank in range(int(seed.sum()),COUNT//2):
 v=void(m,f);ranks.flat[v]=rank;m.flat[v]=True;f+=stamp(v)
m=~m;f=field(m)
for rank in range(COUNT//2,COUNT):
 c=cluster(m,f);ranks.flat[c]=rank;m.flat[c]=False;f-=stamp(c)
assert np.array_equal(np.sort(ranks.ravel()),np.arange(COUNT))
root=Path(__file__).resolve().parents[1]
lines=['// Generated by tools/generate_blue_noise.py; deterministic void-and-cluster ranks.','const blueNoiseSize = 128;','const blueNoiseRanks = <int>[']
lines += ['  '+','.join(map(str,row))+',' for row in ranks]
lines+= ['];']
(root/'app/lib/imaging/blue_noise.dart').write_text('\n'.join(lines)+'\n',encoding='utf-8')
# Compare low frequency power against an equally dense shuffled pattern.
def low_power(binary):
 spectrum=np.abs(np.fft.fftshift(np.fft.fft2(binary-binary.mean())))**2
 yy,xx=np.ogrid[-N//2:N//2,-N//2:N//2];r=xx*xx+yy*yy
 return float(spectrum[(r>0)&(r<10**2)].mean())
mask=ranks<COUNT//2;white=rng.permutation(mask.ravel()).reshape(N,N)
print({'seed_iterations':iteration,'low_frequency_power_blue':low_power(mask),'low_frequency_power_random':low_power(white)})
